"""Writes js/i18n-ne.js from scripts/ne_dict.py."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from ne_dict import NE
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, "js", "i18n-ne.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* Nepali translations — generated by scripts/build_i18n.py from scripts/ne_dict.py. Do not edit by hand. */\n")
    f.write("window.VCOH_NE = " + json.dumps(NE, ensure_ascii=False, indent=0) + ";\n")
print(len(NE), "entries ->", out)
